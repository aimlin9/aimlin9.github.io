#!/usr/bin/env node
// Regenerates src/data/projects.ts from a GitHub user's public, non-fork repos.
// Usage: node scripts/fetch-github-repos.mjs <github-username> [--limit 6]

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const [, , username, ...rest] = process.argv;
const limitFlagIndex = rest.indexOf("--limit");
const limit = limitFlagIndex !== -1 ? Number(rest[limitFlagIndex + 1]) : 6;

if (!username) {
  console.error("Usage: node scripts/fetch-github-repos.mjs <github-username> [--limit 6]");
  process.exit(1);
}

const res = await fetch(
  `https://api.github.com/users/${username}/repos?sort=updated&per_page=100`,
  { headers: { Accept: "application/vnd.github+json" } }
);

if (!res.ok) {
  console.error(`GitHub API request failed: ${res.status} ${res.statusText}`);
  process.exit(1);
}

const repos = await res.json();

const picked = repos
  .filter((r) => !r.fork && !r.archived)
  .sort((a, b) => b.stargazers_count - a.stargazers_count || new Date(b.pushed_at) - new Date(a.pushed_at))
  .slice(0, limit);

const sizes = ["lg", "md", "md", "sm", "sm", "sm"];

const projects = picked.map((r, i) => ({
  title: r.name.replace(/[-_]/g, " ").replace(/\b\w/g, (c) => c.toUpperCase()),
  description: r.description || "No description yet — add one on GitHub.",
  tags: [r.language, ...(r.topics || [])].filter(Boolean).slice(0, 3),
  href: r.html_url,
  size: sizes[i] ?? "sm",
  featured: i === 0,
}));

const fileContents = `// Auto-generated by scripts/fetch-github-repos.mjs — do not hand-edit.
// Regenerate with: node scripts/fetch-github-repos.mjs ${username}
export type Project = {
  title: string;
  description: string;
  tags: string[];
  href: string;
  size: "lg" | "md" | "sm";
  featured?: boolean;
};

export const projects: Project[] = ${JSON.stringify(projects, null, 2)};
`;

const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "data",
  "projects.ts"
);

await writeFile(outPath, fileContents, "utf-8");
console.log(`Wrote ${picked.length} projects to src/data/projects.ts`);
